# --- play / genmove --------------------------------------------------------------------

def test_play_translates_vertex_and_color():
    engine, game = _engine()
    assert engine.send("play black D4") == _ok()   # D = 4th column (GTP skips I)
    assert engine.send("play white Q16") == _ok()
    board = game._state.get_board()
    # GTP rows count up from the bottom; the engine's y counts down from the top
    assert game._state.get_history() == [(3, 15), (15, 3)]
    assert board[3][15] == go.BLACK and board[15][3] == go.WHITE


def test_play_same_color_twice_uses_the_given_color():
    engine, game = _engine()
    engine.send("play black D4")
    engine.send("play black Q16")
    assert game._state.get_board()[15][3] == go.BLACK


# --- orientation: GTP counts rows from the bottom, SGF (and the engine) from the top ------

def test_gtp_game_is_oriented_like_its_sgf_record():
    """A position arriving over GTP matches the same game read from SGF, so the network
    sees KGS games exactly as it would see their downloaded records."""
    engine, game = _engine()
    engine.send("play black C3")
    engine.send("play white Q16")
    assert game._state.get_history() == sgf_to_gamestate(
        "(;GM[1]SZ[19];B[cq];W[pd])").get_history()


def test_sgf_sent_to_gnugo_uses_standard_coordinates():
    engine, game = _engine()
    engine.send("play black C3")
    engine.send("play white Q16")
    path = game.get_current_state_as_sgf()
    try:
        with open(path) as f:
            text = f.read()
    finally:
        os.remove(path)
    assert ";B[cq]" in text and ";W[pd]" in text


@pytest.mark.parametrize("size,vertex", [(19, "C3"), (19, "Q16"), (19, "T19"), (19, "A1"),
                                         (9, "C3"), (9, "J9"), (13, "N1")])
def test_vertex_round_trips_through_the_engine(size, vertex):
    """A move played at a vertex and then generated by the engine comes back as that same
    vertex - on any board size."""
    engine, game = _engine()
    engine.send("boardsize {}".format(size))
    engine.send("play black " + vertex)
    [played] = game._state.get_history()
    engine, _ = _engine(ScriptedPlayer([played]))
    engine.send("boardsize {}".format(size))
    assert engine.send("genmove black") == _ok(vertex)


